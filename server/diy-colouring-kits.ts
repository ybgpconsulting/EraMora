export function ensureDiyColouringKitCatalog(
  categories: Category[],
  products: Product[],
  createdAt = new Date().toISOString()
): void {
  let category = categories.find(
    (item) => item.slug === DIY_COLOURING_KITS_CATEGORY.slug || item.id === DIY_COLOURING_KITS_CATEGORY.id
  );
  if (!category) {
    category = { ...DIY_COLOURING_KITS_CATEGORY };
    categories.push(category);
  } else {
    category.name = DIY_COLOURING_KITS_CATEGORY.name;
    category.slug = DIY_COLOURING_KITS_CATEGORY.slug;
    category.description = DIY_COLOURING_KITS_CATEGORY.description;
  }

  for (const product of createDiyColouringKitProducts(createdAt)) {
    product.categoryId = category.id;
    const sku = product.variants[0].sku;
    const normalizedName = product.name.trim().toLowerCase();
    const hasProductName = (item: Product) =>
      typeof item.name === 'string' && item.name.trim().toLowerCase() === normalizedName;
    const existing = products.find(
      (item) =>
        item.id === product.id ||
        item.slug === product.slug ||
        hasProductName(item)
    );
    const skuOwner = products.find(
      (item) => Array.isArray(item.variants) && item.variants.some((variant) => variant.sku === sku)
    );

    if (skuOwner && existing && skuOwner !== existing) {
      throw new Error(`Cannot add ${product.name}: SKU ${sku} is already assigned to another product.`);
    }
    if (skuOwner && !existing && !hasProductName(skuOwner)) {
      throw new Error(`Cannot add ${product.name}: SKU ${sku} is already assigned to another product.`);
    }
    const target = existing || skuOwner;

    if (!target) {
      products.push(product);
      continue;
    }

    const existingVariants = Array.isArray(target.variants) ? target.variants : [];
    const existingVariant =
      existingVariants.find((variant) => variant.sku === sku) || existingVariants[0];
    Object.assign(target, product, {
      createdAt: target.createdAt || product.createdAt,
      variants: [
        {
          ...product.variants[0],
          id: existingVariant?.id || product.variants[0].id,
          stock:
            existingVariant && Number.isSafeInteger(existingVariant.stock) && existingVariant.stock >= 0
              ? existingVariant.stock
              : 0,
        },
      ],
    });
  }
}
